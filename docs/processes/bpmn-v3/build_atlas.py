"""Create a standalone Word atlas of the current, visually checked BPMN."""
from pathlib import Path
import importlib.util
import json
import sys
from docx import Document
from docx.shared import Inches, Pt
from docx.oxml.ns import qn

BASE=Path(__file__).parent
ROOT=BASE.parents[2]
helper_spec=importlib.util.spec_from_file_location('word_helpers',BASE.parent/'bpmn-v2/build_word.py')
h=importlib.util.module_from_spec(helper_spec)
helper_spec.loader.exec_module(h)
models=ROOT/'output/bpmn-v3/models'
images=ROOT/'output/bpmn-v3/images'
index=json.loads((models/'model-index.json').read_text('utf-8'))
reports=json.loads((images/'render-report.json').read_text('utf-8'))
assert len(reports)==18 and all(x['importWarnings']==0 and x['editAndReimport'] for x in reports)
doc=Document()
h.setup(doc)
s=doc.sections[0]
s.page_width,s.page_height=Inches(8.5), Inches(11)
s.header.paragraphs[0].text='Хомыч   BPMN версии 3   11 ноября 2026'
doc.styles['Normal'].font.size=Pt(11)
doc.styles['Table Text'].font.size=Pt(10.5)
doc.core_properties.title='Процессы продукта Хомыч по функциональным требованиям'
doc.core_properties.author='Команда проекта Хомыч'
h.para(doc,'Процессы продукта Хомыч','Title')
h.para(doc,'BPMN по функциональным требованиям версии 0 2','Subtitle')
h.para(doc,'Редакция 3 от 11 ноября 2026 года. Актуальный сборник для команды разработки. В него входят 18 отдельных схем, связь с 42 требованиями и открытые вопросы.')
h.para(doc,'Стажёр получает сообщения по периодам и задаёт вопросы AI. Руководитель собирает сценарий из готовых блоков, а бадди и руководитель получают соответствующие сообщения о своей помощи. Чек-листы нужны для формального учёта и не управляют переходом между периодами.')
doc.add_heading('Как устроен общий процесс',1)
h.para(doc,'P00 показывает независимые даты программы. P15 раскрывает формирование сообщений одного блока, P16 — доставку одному адресату. Ошибка отправки или незавершённая работа одного участника не задерживают календарь остальных сообщений.')
h.para(doc,'P03–P13 описывают контекст работы людей после сообщения. Действия по ссылкам, встречи, подготовка результатов и кадровые решения выполняются вне продукта. Их наличие на схеме не означает, что приложение проверяет завершение.')
h.para(doc,'P14 описывает личный вопрос стажёра и ответ через RAG. Ответы используют разрешённые материалы. Приватность распространения личных AI ответов ещё требует решения OQ01. P17 — предложение по обновлению источников.')
doc.add_heading('Статус схем',1)
h.para(doc,'Модели P05–P06 и защищённые материалы P07 сохранены как условная интеграция OQ08. Они не становятся обязательными от включения в сборник. Предложения по доставке, версионированию и базе знаний сохраняют статус из требований.')
h.para(doc,'Исходные BPMN редактируются в BPMN Modeler. Изображения в Word служат для чтения. В архиве находятся также SVG для увеличения, таблицы соответствия и исходники. Прежняя редакция 2 сохранена отдельно; этот сборник заменяет её схемы, но не переписывает прежнюю системную спецификацию и OpenAPI.')

h.landscape(doc)
doc.add_heading('Каталог текущих процессов',1)
h.para(doc,'Все схемы читаются слева направо. Часы обозначают календарное ожидание, плюс — независимые ветки, крест — выбор одной ветки. Пунктир между пулами обозначает обмен с внешним сервисом. Модели неисполняемые и описывают поведение для реализации в приложении.')
rows=[['ID','Процесс','Граница','Требований']]
for m in index['models']:
    rows.append([m['id'],m['title'],m['scope'],str(len(m['requirements']))])
h.table(doc,rows,[.65,6.1,6.95,1.55])
h.para(doc,'Исторический источник — 40 строк листа 3 «Чек-лист по ролям». Актуальные изменения заданы функциональными требованиями 0.2 и уточнениями пользователя. Документация узлов сохраняет происхождение, но прежние описания участия AI не отменяют новую концепцию.')

for m in index['models']:
    doc.add_page_break()
    h.para(doc,m['id']+'   '+m['scope'],'Kicker')
    doc.add_heading(m['title'],1)
    h.para(doc,'**Запуск.** '+m['trigger']+'.','Diagram Notes')
    h.para(doc,'**Результат.** '+m['result']+'.','Diagram Notes')
    h.picture(doc,images/(m['id']+'.png'),15.05,6.65,m['id']+' '+m['title'])
    h.para(doc,'**Проверка.** '+m['acceptance'],'Diagram Notes')
    h.para(doc,'**Требования.** '+(', '.join(m['requirements'])+'.' if m['requirements'] else 'Ручной бизнес-контекст без дополнительной операции приложения.'),'Diagram Notes')
    for note in m['notes']:
        h.para(doc,note,'Diagram Notes')

doc.add_page_break()
doc.add_heading('Открытые вопросы',1)
questions=[
 ['OQ01','Какие ответы AI, кроме плановых сообщений, могут получать бадди и руководитель? Как сохраняется приватность содержания вопроса?'],
 ['OQ02','В какой среде работает бот, как устроены вход, звук и доставка при закрытом интерфейсе?'],
 ['OQ03','Когда отправляются сообщения разным ролям и какие дополнительные напоминания нужны?'],
 ['OQ04','Как рассчитываются месяцы и время отправки; как отражаются перенос старта, пауза и замена бадди?'],
 ['OQ05','Что HR делает в приложении и какие сообщения получает?'],
 ['OQ06','Можно ли применять один сценарий к группе и как изменение шаблона отражается на запущенных сценариях?'],
 ['OQ07','Кто отвечает за материалы RAG, их проверку, загрузку и права?'],
 ['OQ08','Какая прямая интеграция с действием остаётся в демо и как используется проверка конкретного доступа первой задачи?'],
]
h.table(doc,[['ID','Нерешённое поведение','Связанные модели']]+[[q,t,', '.join(index['open_questions'][q])] for q,t in questions],[.75,11.1,3.4])
h.para(doc,'Эти вопросы не закрыты автоматически при обновлении схем. Условные ветви и предложения можно реализовывать после соответствующего решения команды. Источники HR, доступ к корпоративным системам и новые требования организаторов не предполагаются.')
doc.add_heading('Что проверено в этой поставке',1)
h.para(doc,'Все модели прошли проверку XML по XSD BPMN, связности и выходов развилок. Все 42 ID требований и 40 строк исторического чек-листа имеют соответствие в узлах. Каждый файл открыт, изменён, сохранён и повторно импортирован без предупреждений. Дополнительно проверены независимость календаря, основной путь по ссылке и условность прямой интеграции.')
h.para(doc,'Визуальная проверка охватывает изображения и страницы сборника. Проверки схем не заменяют тесты будущего приложения. Технические имена параметров дат в формулах являются проектными обозначениями, а не готовыми контрактами API.')

doc.add_page_break()
doc.add_heading('Связь функциональных требований с узлами',1)
h.para(doc,'Статус взят из требований версии 0.2. Поскольку часть узлов изменила смысл, при передаче задачи используйте номер редакции и текст требования вместе с ID узла.')
rows=[['ID','Требование','Статус','Узлы BPMN']]
for rid,r in index['requirements'].items():
    rows.append([rid,r['name'],r['status'],', '.join(index['requirement_nodes'][rid])])
h.table(doc,rows,[1.1,5.1,2.15,6.9])
doc.add_heading('Источники и следующие документы',1)
h.para(doc,'Основание — функциональные требования продукта Хомыч, версия 0.2 от 11 ноября 2026 года, и явные уточнения в обсуждении. Исторический чек-лист взят из сохранённого диапазона A1:F41. Онлайн лист и PDF кейса в этой редакции повторно не сверялись.')
h.para(doc,'Перед реализацией новых функций требуется согласовать MVP и обновить экраны, модель данных, API и задания разработки под текущую концепцию. Предыдущие контракты прототипа продолжают описывать прежнюю границу, а не весь объём этих схем.')
for style in doc.styles:
    for border in list(style.element.iter(qn('w:pBdr'))):
        border.getparent().remove(border)
out=ROOT/'output/ai-buddy-bpmn-v3.docx'
doc.save(out)
print(out)
